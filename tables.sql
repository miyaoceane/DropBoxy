CREATE TABLE POINT_RELAIS (
    IdPoint INT PRIMARY KEY,
    Nom VARCHAR(100) NOT NULL,
    Adresse VARCHAR(255) NOT NULL,
    Ville VARCHAR(100) NOT NULL,
    CodePostal VARCHAR(10) NOT NULL,
    Statut VARCHAR(30) NOT NULL
);

CREATE TABLE CASIER (
    IdCasier INT PRIMARY KEY,
    IdPoint INT NOT NULL,
    Numero INT NOT NULL,
    Taille VARCHAR(20) NOT NULL,
    Statut VARCHAR(30) NOT NULL,

    CONSTRAINT FK_CASIER_POINT_RELAIS
        FOREIGN KEY (IdPoint) REFERENCES POINT_RELAIS(IdPoint)
);

CREATE TABLE CLIENT (
    IdClient INT PRIMARY KEY,
    Nom VARCHAR(100) NOT NULL,
    Prenom VARCHAR(100) NOT NULL,
    Email VARCHAR(255) NOT NULL,
    Telephone VARCHAR(20) NOT NULL
);

CREATE TABLE COLIS (
    IdColis INT PRIMARY KEY,
    IdClient INT NOT NULL,
    IdPointDepot INT NOT NULL,
    IdCasier INT NOT NULL,
    DateDepot DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    Poids DECIMAL(10,2) NOT NULL,
    Taille VARCHAR(20) NOT NULL,
    Statut VARCHAR(30) NOT NULL,

    CONSTRAINT FK_COLIS_CLIENT
        FOREIGN KEY (IdClient) REFERENCES CLIENT(IdClient),

    CONSTRAINT FK_COLIS_POINT_RELAIS
        FOREIGN KEY (IdPointDepot) REFERENCES POINT_RELAIS(IdPoint),

    CONSTRAINT FK_COLIS_CASIER
        FOREIGN KEY (IdCasier) REFERENCES CASIER(IdCasier),

    CONSTRAINT CK_COLIS_POIDS
        CHECK (Poids > 0)
);

CREATE TABLE RETRAIT (
    IdRetrait INT PRIMARY KEY,
    IdColis INT NOT NULL,
    DateRetrait DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    CodeRetrait VARCHAR(50) NOT NULL,

    CONSTRAINT FK_RETRAIT_COLIS
        FOREIGN KEY (IdColis) REFERENCES COLIS(IdColis)
);

CREATE TABLE TECHNICIEN (
    IdTechnicien INT PRIMARY KEY,
    Nom VARCHAR(100) NOT NULL,
    Prenom VARCHAR(100) NOT NULL,
    Specialite VARCHAR(100) NOT NULL,
    Email VARCHAR(255) NOT NULL
);

CREATE TABLE INCIDENT (
    IdIncident INT PRIMARY KEY,
    IdPoint INT NOT NULL,
    IdCasier INT NOT NULL,
    IdTechnicien INT NOT NULL,
    DateIncident DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    TypeIncident VARCHAR(100) NOT NULL,
    Description VARCHAR(1000),
    Statut VARCHAR(30) NOT NULL,
    DateResolution DATETIME2 NULL,

    CONSTRAINT FK_INCIDENT_POINT_RELAIS
        FOREIGN KEY (IdPoint) REFERENCES POINT_RELAIS(IdPoint),

    CONSTRAINT FK_INCIDENT_CASIER
        FOREIGN KEY (IdCasier) REFERENCES CASIER(IdCasier),

    CONSTRAINT FK_INCIDENT_TECHNICIEN
        FOREIGN KEY (IdTechnicien) REFERENCES TECHNICIEN(IdTechnicien),

    CONSTRAINT CK_INCIDENT_DATES
        CHECK (DateResolution IS NULL OR DateResolution >= DateIncident)
);
